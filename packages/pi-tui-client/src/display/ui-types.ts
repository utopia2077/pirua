import type { KeybindingsManager } from "../core/keybindings.ts";
export type WidgetPlacement = "aboveEditor" | "belowEditor";
export type TerminalInputHandler = (data: string) => { consume?: boolean; data?: string } | undefined;
export interface MarkdownTransformContext {
	messageType: "user" | "assistant" | "assistant-thinking";
	isStreaming: boolean;
	availableWidth: number;
}
export interface ToolDefinition<TParams = any, TDetails = any, TState = any> {
	name?: string;
	description?: string;
	parameters?: Record<string, unknown>;
	renderShell?: "default" | "self";
	renderCall?: (args: TParams, theme: Theme, context: ToolRenderContext<TState, TParams>) => Component;
	renderResult?: (
		result: ToolResult & { details?: TDetails },
		options: ToolRenderResultOptions,
		theme: Theme,
		context: ToolRenderContext<TState, TParams>,
	) => Component;
}
type AnyToolDefinition = ToolDefinition;

